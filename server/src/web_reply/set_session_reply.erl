-spec new
(
	non_neg_integer(),
	binary(),
	binary(),
	list(user_db_entry:room())
)
-> web_reply:fragment().
new (Version, Username, Token, PendingRooms) ->
	{
		[
			{?MESSAGE_FIELD, ?SET_SESSION_REPLY_ID},
			{?USER_ID_FIELD, Username},
			{?SESSION_TOKEN_FIELD, Token},
			{?USER_VERSION_FIELD, Version},
			{
				?PENDING_ROOMS_FIELD,
				pending_rooms_update_reply:embedded(PendingRooms)
			}
		]
	}.
