-spec new (room_db_entry:type(), ataxia_id:type()) -> web_reply:fragment().
new (Room, _Username) ->
	% For now, all users have the same visibility (_Username unused). This is
	% likely to change in the future.
	{
		[
			{?MESSAGE_FIELD, ?SET_ROOM_REPLY_ID},
			{?ROOM_FIELD, room_db_entry:encode(Room)}
		]
	}.
