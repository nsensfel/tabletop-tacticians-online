-spec credentials_match
	(
		binary(),
		ataxia_id:type(),
		ataxia_lock_client:janitor()
	) -> boolean().
credentials_match (SessionToken, UserID, LockJanitor) ->
	case ataxia_lock_client:request_read_lock(LockJanitor, user_db, UserID) of
		{ok, Lock} ->
			Result =
				case ataxia_client:fetch(user_db, UserID, Lock) of
					{ok, _Version, Value} ->
						user_db_entry:has_token(SessionToken, Value);

					Error -> false
				end,
			ataxia_lock_client:release(LockJanitor, Lock),
			Result;

		_ -> false
	end.
